/**
 * Build the inline "boot" stylesheet in index.html.
 *
 * styles.css is 93 KB and, as a plain <link>, holds up first paint behind a
 * whole round trip. The page's first frame is the intro overlay, which is a
 * fixed, full-screen cover — so if the handful of rules that paint it are
 * inlined, the page can paint immediately and fetch the real stylesheet
 * without blocking.
 *
 * The rules are COPIED OUT OF styles.css rather than written by hand, so
 * there is one source for every value. Run this after editing any of the
 * selectors listed below; boot.test.mjs fails if the inline block and
 * styles.css have drifted apart, so a forgotten run is caught rather than
 * shipped.
 *
 *   node tools/boot-css.mjs          rewrite index.html
 *   node tools/boot-css.mjs --check  exit 1 if it is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';

const START = '<!-- BOOT-CSS:START — generated by tools/boot-css.mjs, do not edit by hand -->';
const END = '<!-- BOOT-CSS:END -->';

// Everything needed to paint the overlay and the page behind it, in the
// order styles.css declares it. Order matters: the cascade is the cascade.
const WANTED = [
  ':root',
  'body.gt4-mode',
  '*, *::before, *::after',
  'html',
  'html, body',
  'body',
  '.lights-out',
  '.lights-out.hidden',
  '.intro-track-line',
  '.intro-car',
  '@keyframes carDrive',
  '.intro-title',
  '.intro-fge',
  '.intro-sub',
  '@keyframes introFadeIn',
];

/**
 * Walk the stylesheet brace by brace and return each top-level block with
 * its selector. A regex cannot do this: @keyframes nests, and several of
 * these rules contain braces inside values.
 */
function topLevelBlocks(css) {
  const out = [];
  let i = 0;
  while (i < css.length) {
    // Skip comments and whitespace between blocks.
    if (css.startsWith('/*', i)) { i = css.indexOf('*/', i) + 2; continue; }
    if (/\s/.test(css[i])) { i++; continue; }

    const open = css.indexOf('{', i);
    if (open === -1) break;
    const selector = css.slice(i, open).replace(/\s+/g, ' ').trim();

    let depth = 0, j = open;
    for (; j < css.length; j++) {
      if (css[j] === '{') depth++;
      else if (css[j] === '}') { depth--; if (depth === 0) { j++; break; } }
    }
    out.push({ selector, text: css.slice(i, j).trim() });
    i = j;
  }
  return out;
}

function build() {
  const css = readFileSync(new URL('../styles.css', import.meta.url), 'utf8');
  const blocks = topLevelBlocks(css);
  const picked = [];

  for (const want of WANTED) {
    const hit = blocks.find(b => b.selector === want);
    if (!hit) throw new Error(`boot-css: "${want}" is not a top-level rule in styles.css any more`);
    picked.push(hit.text);
  }

  // Not copied from a block of its own: styles.css turns the car animation
  // off inside a larger prefers-reduced-motion rule, and the overlay must
  // respect that before the full sheet arrives.
  picked.push('@media (prefers-reduced-motion: reduce) { .intro-car { animation: none; } }');

  return picked.join('\n');
}

const inline = build();
const path = new URL('../index.html', import.meta.url);
const html = readFileSync(path, 'utf8');

const a = html.indexOf(START), b = html.indexOf(END);
if (a === -1 || b === -1) throw new Error('boot-css: the BOOT-CSS markers are missing from index.html');

const current = html.slice(a + START.length, b);
const next = `\n    <style>\n${inline}\n    </style>\n    `;

if (process.argv.includes('--check')) {
  if (current.trim() !== next.trim()) {
    console.error('boot CSS in index.html is out of date — run: node tools/boot-css.mjs');
    process.exit(1);
  }
  console.log('boot CSS is up to date');
} else {
  writeFileSync(path, html.slice(0, a + START.length) + next + html.slice(b));
  console.log(`boot CSS written — ${(inline.length / 1024).toFixed(1)} KB inline`);
}
